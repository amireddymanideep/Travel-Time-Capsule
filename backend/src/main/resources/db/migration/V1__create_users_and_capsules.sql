CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE capsules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    destination VARCHAR(150) NOT NULL,
    location VARCHAR(300),
    coordinates VARCHAR(100),
    travel_date DATE NOT NULL,
    unlock_date DATE NOT NULL,
    companions VARCHAR(500),
    expenses NUMERIC(12, 2),
    description TEXT,
    note TEXT,
    video_url VARCHAR(2048),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT capsule_unlock_date_after_travel CHECK (unlock_date >= travel_date)
);

CREATE INDEX capsules_user_travel_date_idx ON capsules (user_id, travel_date DESC);

CREATE TABLE capsule_photos (
    capsule_id BIGINT NOT NULL REFERENCES capsules(id) ON DELETE CASCADE,
    photo_order INTEGER NOT NULL,
    photo_url TEXT NOT NULL,
    PRIMARY KEY (capsule_id, photo_order)
);
